package amount

import "testing"

func TestParse(t *testing.T) {
	// ทุกข้อความมาจากผล OCR จริงตอน spike
	cases := []struct {
		in   string
		want Satang
		ok   bool
	}{
		{"119.00 บาท", 11900, true},
		{"29,311.00THB", 2931100, true},    // BBL ติดหน่วยไม่มีช่องว่าง
		{"31.700.00", 3170000, true},       // จุลภาคกลายเป็นจุด
		{"3.423.98", 342398, true},         // เช่นเดียวกัน แต่ทศนิยมไม่ใช่ 00
		{"20 บาท", 2000, true},             // ไม่มีทศนิยม
		{"0 บาท", 0, true},                 // ค่าธรรมเนียม K PLUS บางใบ
		{"81.60 บาท", 8160, true},          // ทศนิยมจริงของเป๋าตัง
		{"19.50MD", 1950, true},            // บรรทัดสินค้า 7-Eleven มีรหัสท้าย
		{"จำนวน: 119.00 บาท", 11900, true}, // คำนำหน้าอยู่บรรทัดเดียวกัน
		{"1,690.00 บาท", 169000, true},
		{"10,000.00 บาท", 1000000, true},
		{"17,600.00 บาท", 1760000, true},
		{"4,000.00", 400000, true},
		{"1234567", 123456700, true}, // 7 หลักยังพอเป็นเงินได้
		{"-27 บาท", 0, false},        // ส่วนลด — ยอดที่บันทึกต้องไม่ติดลบ
		{"-122.40 บาท", 0, false},
		{"TID#2026091400000005239383499", 0, false}, // เลขอ้างอิงยาว ไม่มีทศนิยม
		{"672878907298DQR65814", 0, false},
		{"xxx-x-x1234-x", 0, false}, // เลขบัญชี: 4 หลักติดกันแต่มีตัวอักษรประกบ → ไม่นับ
		{"081-xxx-2222", 0, false},
		{"ค่าธรรมเนียม", 0, false},
		{"", 0, false},
		{"2 ชิ้น", 200, true}, // ผู้เรียก (7-Eleven) ต้องข้ามเอง — Parse ไม่รู้บริบท
	}
	for _, c := range cases {
		got, ok := Parse(c.in)
		if ok != c.ok || got != c.want {
			t.Errorf("Parse(%q) = (%d, %v) ต้องการ (%d, %v)", c.in, got, ok, c.want, c.ok)
		}
	}
}

func TestSplitDecimal(t *testing.T) {
	cases := []struct {
		in          string
		whole, frac string
	}{
		{"119.00", "119", "00"},
		{"29,311.00", "29311", "00"},
		{"31.700.00", "31700", "00"},
		{"3.423.98", "3423", "98"},
		{"20", "20", ""},
		{"81.6", "81", "6"},
		{"1.234", "1234", ""}, // จุดเดียวแต่ตามด้วย 3 หลัก = ตัวคั่นหลักพัน ไม่ใช่ทศนิยม
	}
	for _, c := range cases {
		whole, frac := splitDecimal(c.in)
		if whole != c.whole || frac != c.frac {
			t.Errorf("splitDecimal(%q) = (%q, %q) ต้องการ (%q, %q)", c.in, whole, frac, c.whole, c.frac)
		}
	}
}
